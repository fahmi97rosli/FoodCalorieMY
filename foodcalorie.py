def convert_food_calorie_txt(
    input_file,
    output_file="bank_kalori_makanan.csv"
):
    """
    Convert a food calorie TXT file into a structured CSV file.

    Parameters:
        input_file (str): Path to the input TXT file.
        output_file (str): Path to save the output CSV.

    Returns:
        pd.DataFrame: Processed food calorie dataset.
    """

    # Read TXT file
    with open(input_file, "r", encoding="utf-8") as file:
        text = file.read()

    topics = {}
    current_topic = None
    current_subtopic = None

    lines = text.splitlines()

    for i, line in enumerate(lines):

        if not line.strip():
            continue

        line = line.strip()

        # Main heading: Roman numeral
        if re.match(r'^[ivxlcdm]+\)\s', line, re.IGNORECASE):
            current_topic = line
            topics[current_topic] = {}
            current_subtopic = None

        # Skip table header
        elif line.startswith("Makanan"):
            continue

        # Detect subtopic using previous empty line
        elif i > 0 and not lines[i-1].strip():
            if current_topic:
                current_subtopic = line
                topics[current_topic][current_subtopic] = []

        # Table data
        else:
            if current_topic and current_subtopic:
                columns = re.split(r'\s{2,}', line)

                if len(columns) == 5:
                    topics[current_topic][current_subtopic].append(columns)

    # Flatten dictionary into records
    data = []

    for topic, subtopics in topics.items():

        for subtopic, records in subtopics.items():

            for record in records:
                data.append([
                    topic,
                    subtopic,
                    *record
                ])

    # Create DataFrame
    df = pd.DataFrame(data, columns=[
        "Topic",
        "Subtopic",
        "Makanan",
        "Hidangan",
        "Berat (g)",
        "Kalori (kcal)",
        "Rujukan"
    ])

    # Convert numeric columns
    df["Berat (g)"] = pd.to_numeric(
        df["Berat (g)"], errors="coerce"
    )

    df["Kalori (kcal)"] = pd.to_numeric(
        df["Kalori (kcal)"], errors="coerce"
    )

    # Clean topic names
    df["Topic"] = df["Topic"].replace({
        "i) BUKAN VEGETARIAN": "BUKAN VEGETARIAN",
        "ii) VEGETARIAN": "VEGETARIAN"
    })

    # Export CSV
    df.to_csv(
        output_file,
        index=False,
        encoding="utf-8-sig"
    )

    print(f"Successfully converted {len(df)} records.")
    print(f"Saved to: {output_file}")

    return df

# Load the pre-trained CLIP model and processor once.
# Loading them outside the function avoids repeatedly downloading
# or initializing the model every time an image is ranked.
model = CLIPModel.from_pretrained(
    "openai/clip-vit-base-patch32"
)

processor = CLIPProcessor.from_pretrained(
    "openai/clip-vit-base-patch32"
)

# Set the model to evaluation mode (disable training-specific behavior).
model.eval()


def get_image_link_rank(query):
    """
    Search for images related to a query and rank them using CLIP.

    Parameters:
        query (str): Search keyword, e.g. "Nasi Lemak".

    Returns:
        dict: Highest-ranked image containing:
            - Makanan: Original search query.
            - score: CLIP similarity score.
            - image_url: Direct URL of the image.
            - source_url: Original webpage containing the image.

        None: If no valid images are found.
    """

    # Search for up to 10 images using DuckDuckGo.
    with DDGS() as ddgs:
        results = ddgs.images(query, max_results=10)

    # Store successfully downloaded and ranked images.
    ranked_images = []

    # Set browser-like HTTP headers to reduce the chance of being blocked.
    headers = {
        "User-Agent": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
            "AppleWebKit/537.36 Chrome/120.0.0.0 Safari/537.36"
        ),
        "Accept": "image/avif,image/webp,image/png,image/*,*/*;q=0.8"
    }

    # Iterate through the image search results.
    for result in results:

        # Extract the direct image URL.
        image_url = result.get("image")

        # Skip results without an image URL.
        if not image_url:
            continue

        try:
            # Download the image using an HTTP GET request.
            response = requests.get(
                image_url,
                timeout=15,
                headers=headers
            )

            # Raise an exception if the HTTP request fails.
            response.raise_for_status()

            # Check whether the response contains a valid image content type.
            content_type = response.headers.get(
                "Content-Type", ""
            )

            if not content_type.startswith("image/"):
                continue

            # Convert the downloaded image into RGB format.
            image = Image.open(
                BytesIO(response.content)
            ).convert("RGB")

            # Preprocess the text query and image into CLIP-compatible tensors.
            inputs = processor(
                text=[query],
                images=image,
                return_tensors="pt",
                padding=True
            )

            # Perform inference without calculating gradients.
            # This reduces memory usage and speeds up prediction.
            with torch.inference_mode():
                outputs = model(**inputs)

            # Extract the image-text similarity score from CLIP.
            score = outputs.logits_per_image.item()

            # Store the image details and its similarity score.
            ranked_images.append({
                "Makanan": query,
                "score": score,
                "image_url": image_url,
                "source_url": result.get("url")
            })

        # Handle HTTP-related errors during image downloading.
        except requests.exceptions.HTTPError as e:
            print(f"HTTP Error {response.status_code}: {image_url}")

        # Handle other errors, such as invalid images or processing failures.
        except Exception as e:
            print(f"Failed: {str(e)[:100]}")

    # Return None if no valid images were successfully processed.
    if not ranked_images:
        return None

    # Sort images by CLIP similarity score in descending order.
    # The highest-scoring image is considered the best match.
    ranked_images.sort(
        key=lambda x: x["score"],
        reverse=True
    )

    # Return the image with the highest similarity score.
    return ranked_images[0]

def get_image_link(query):
    """
    Search for an image based on the given query.

    Parameters:
        query (str): Search keyword, e.g. "Nasi Lemak".

    Returns:
        tuple: Contains:
            - image_url: Direct URL of the image.
            - source_url: Original webpage containing the image.

        None: If no search results are found.
    """

    # Search for images using DuckDuckGo.
    # Retrieve only the first matching image.
    with DDGS() as ddgs:
        results = ddgs.images(query, max_results=1)

    # Return None if no image search results are found.
    if not results:
        return None

    # Extract and return the direct image URL and its source webpage URL.
    return results[0].get("image"), results[0].get("url")

def fetch_image(data, column):
    """
    Fetch image URLs for unique elements in a specified DataFrame column.

    Parameters:
        data (pd.DataFrame): Input DataFrame containing the search keywords.
        column (str): Column name containing the elements to search for.

    Returns:
        pd.DataFrame: DataFrame containing:
            - Makanan: Original search keyword.
            - image_url: Direct URL of the image.
            - source_url: Original webpage containing the image.

        Returns an empty DataFrame if an error occurs.
    """

    # Initialize an empty DataFrame and list to store image search results.
    dfs = pd.DataFrame()
    data_image = []

    # Extract unique elements from the specified column.
    element_list = list(data[column].unique())

    try:
        # Initialize the progress counter.
        num = 0

        # Iterate through each unique element and search for its image.
        for element in element_list:

            # Retrieve the direct image URL and its source webpage URL.
            image_url, source_url = get_image_link(element)

            # Store the search results in a dictionary.
            data_image.append({
                "Makanan": element,
                "image_url": image_url,
                "source_url": source_url
            })

            # Update the progress counter.
            num = num + 1

            # Display the number of completed searches.
            print(f"{num} of {len(element_list)} completed")

        # Convert the collected image results into a DataFrame.
        dfs = pd.DataFrame(data_image)

        # Return the DataFrame containing all image search results.
        return dfs

    # Handle errors during the image retrieval process.
    except Exception as e:
        print(f"Error fetching images: {e}")

        # Return the results collected so far as a DataFrame.
        return pd.DataFrame(data_image)

def fetch_image_rank(data, column):
    """
    Fetch and rank images for unique elements in a specified DataFrame column
    using the CLIP model.

    Parameters:
        data (pd.DataFrame): Input DataFrame containing the search keywords.
        column (str): Column name containing the elements to search for.

    Returns:
        pd.DataFrame: DataFrame containing:
            - Makanan: Original search keyword.
            - score: CLIP image-text similarity score.
            - image_url: Direct URL of the selected image.
            - source_url: Original webpage containing the image.

        Returns an empty DataFrame if an error occurs.
    """

    # Initialize an empty DataFrame and list to store ranked image results.
    dfs = pd.DataFrame()
    data_image = []

    # Extract unique elements from the specified column.
    element_list = list(data[column].unique())

    try:
        # Initialize the progress counter.
        num = 0

        # Iterate through each unique element and find its best-matching image.
        for element in element_list:

            # Search for images and select the highest-ranked result using CLIP.
            data_image.append(get_image_link_rank(element))

            # Update the progress counter.
            num = num + 1

            # Display the number of completed image searches.
            print(f"{num} of {len(element_list)} completed")

        # Convert the collected ranked image results into a DataFrame.
        dfs = pd.DataFrame(data_image)

        # Return the DataFrame containing the selected images.
        return dfs

    # Handle errors during image retrieval and ranking.
    except Exception as e:
        print(f"Error ranking images: {e}")

        # Return successfully collected results if an error occurs midway.
        return pd.DataFrame(data_image)

def generate_food_image_dataset(
    input_file,
    output_file="bank_kalori_makanan_link.csv"
):
    """
    Generate a food calorie dataset with image links.

    Parameters:
        input_file (str): Path to the food calorie CSV file.
        output_file (str): Path to save the merged CSV file.

    Returns:
        pd.DataFrame: Dataset containing food information and image links.
    """

    # Read food calorie dataset
    data = pd.read_csv(input_file)

    # Remove duplicate food names, keeping the last occurrence
    data = (
        data.drop_duplicates(subset=["Makanan"], keep="last")
            .reset_index(drop=True)
    )

    # Fetch image links for each food item
    # Use fetch_image_rank(data, "Makanan") if image ranking is preferred
    df_makanan_link = fetch_image(data, "Makanan")

    # Merge image links with the original food dataset
    df_merge = pd.merge(
        data,
        df_makanan_link,
        on="Makanan",
        how="left"
    )

    # Export the merged dataset to CSV
    df_merge.to_csv(
        output_file,
        index=False,
        encoding="utf-8-sig"
    )

    # Display processing summary
    print(f"Total food records: {len(data)}")
    print(f"Total records with image data: {df_merge['image_link'].notna().sum()}")
    print(f"Saved to: {output_file}")

    return df_merge

